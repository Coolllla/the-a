// 时间轴的年月换算。
//
// 时间轴要把「什么时候」变成「轴上第几像素」，就得先有一个能减、能比的数值。
// 这里统一约定：**真小数年** —— 整数部分是年，小数部分是这一年过去的比例。
//
// 为什么不直接把年月拼成 2023.3 那样：那不是小数年。11 月拼出的 .11
// 在数值上小于 9 月的 .9，只要出现两位数月份，节点顺序必然排错。

/**
 * 年 + 月 → 真小数年。
 *
 *   ym(2023, 3)   // 2023 年 3 月  → 2023.1666…
 *   ym(2023, 11)  // 2023 年 11 月 → 2023.8333…
 *   ym(2023)      // 只知道年份    → 2023（落在这一年的起点）
 *
 * 月份可以省。省了、或者填了 0 / 负数，都当 1 月处理 —— 也就是「偏移量为 0，
 * 落在整年刻度上」。故意不做范围校验：填 13 就是次年 1 月，跨年写法照样能用。
 */
export function ym(year: number, month = 1): number {
  return year + (Math.max(1, month) - 1) / 12;
}
